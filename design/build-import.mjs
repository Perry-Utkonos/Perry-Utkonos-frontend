import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
import vm from 'node:vm'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n')
const state = JSON.parse(read('design/figma-state.json'))
const ICONS = JSON.parse(read('design/icons.json'))
const css = read('src/styles/global.css')
const themes = { purple: {}, cream: {} }
for (const [, selectors, body] of css.matchAll(/([^{}]+)\{([^{}]+)\}/g)) {
  if (!selectors.includes(':root')) continue
  const entries = Object.fromEntries([...body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]))
  if (selectors.includes("data-theme='cream'")) Object.assign(themes.cream, entries)
  else { Object.assign(themes.purple, entries); Object.assign(themes.cream, entries) }
}
const aliases = { bg: '--bg', surface: '--surface', elevated: '--surface-light', primary: '--primary', olive: '--olive', text: '--text', muted: '--muted', line: '--line', ink: '--on-primary' }
const rgb = (hex) => {
  if (!/^#(?:[\da-f]{3}|[\da-f]{6})$/i.test(hex)) throw new Error(`Expected an RGB hex color, got ${hex}`)
  hex = hex.slice(1)
  if (hex.length === 3) hex = [...hex].map((char) => char + char).join('')
  return { r: parseInt(hex.slice(0, 2), 16) / 255, g: parseInt(hex.slice(2, 4), 16) / 255, b: parseInt(hex.slice(4, 6), 16) / 255 }
}
const colors = Object.fromEntries(Object.entries(themes).map(([theme, values]) => [theme, Object.fromEntries(Object.entries(aliases).map(([name, variable]) => [name, rgb(values[variable])]))]))
const sources = ['figma-bootstrap.js', 'figma-helpers.js', 'figma-components.js', 'figma-screens.js'].map((file) => read(`design/${file}`))
const fingerprint = createHash('sha256').update(JSON.stringify({ colors, ICONS, state, sources })).digest('hex')
const body = `const CONFIG = ${JSON.stringify({ fileKey: state.fileKey, portrait: state.portrait, fingerprint })};\nconst COLORS = ${JSON.stringify(colors)};\nconst ICONS = ${JSON.stringify(ICONS)};\n${sources.join('\n')}`
// Syntax check before writing a file that will execute in the Plugin API context.
new vm.Script(`(async () => {\n${body}\n})()`)
fs.writeFileSync(path.join(root, 'design/figma-import.generated.js'), `// Generated by npm run design:prepare. Execute the entire body in Figma Plugin API.\n${body}\n`)
fs.writeFileSync(path.join(root, 'design/code.generated.js'), `// Generated by npm run design:prepare.\nasync function importFate() {\n${body}\n}\nimportFate().then(result => { console.log(result); figma.closePlugin('Fate: '+result.status); }).catch(error => { console.error(error); figma.closePlugin('Fate: '+error.message); });\n`)
console.log(`Prepared Figma import: ${fingerprint.slice(0, 12)}; colors read from global.css`)
